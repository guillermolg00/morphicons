/* Extracts the playground's vendored icons from the npm packages installed
   as devDeps (real data, not hand-copied):
   - Feather Icons (MIT) — feather-icons/dist/icons.json (name → innerHTML)
   - Tabler Icons (MIT) — @tabler/icons/tabler-nodes-outline.json (IconNode)
   Regenerate after changing the selection:  bun playground/extract-vendor-icons.mjs */

import { readFileSync, writeFileSync } from "node:fs";

const FEATHER_PICK = [
  "camera",
  "github",
  "settings",
  "scissors",
  "coffee",
  "wifi",
  "cloud-rain",
  "feather",
];

const TABLER_PICK = [
  "cat",
  "ghost",
  "planet",
  "rocket",
  "bolt",
  "brand-github",
  "bike",
  "moon-stars",
];

// Feather contents are flat sequences of elements with quoted attributes —
// a regex is enough (no nesting, no text).
const parseContents = (s) => {
  const nodes = [];
  for (const m of s.matchAll(/<([a-z]+)((?:\s+[\w-]+="[^"]*")*)\s*\/?>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    nodes.push([m[1], attrs]);
  }
  return nodes;
};

const feather = JSON.parse(
  readFileSync("node_modules/feather-icons/dist/icons.json", "utf8"),
);
const tabler = JSON.parse(
  readFileSync("node_modules/@tabler/icons/tabler-nodes-outline.json", "utf8"),
);

const missing = [
  ...FEATHER_PICK.filter((n) => !feather[n]).map((n) => `feather:${n}`),
  ...TABLER_PICK.filter((n) => !tabler[n]).map((n) => `tabler:${n}`),
];
if (missing.length) {
  console.error("Not present in the packages:", missing.join(", "));
  process.exit(1);
}

const featherVersion = JSON.parse(
  readFileSync("node_modules/feather-icons/package.json", "utf8"),
).version;
const tablerVersion = JSON.parse(
  readFileSync("node_modules/@tabler/icons/package.json", "utf8"),
).version;

const entries = (names, get) =>
  names.map((n) => `  "${n}": ${JSON.stringify(get(n))},`).join("\n");

const out = `/* GENERATED by extract-vendor-icons.mjs — do not edit by hand.
   Icon data for the playground, extracted from the devDep packages:
   Feather Icons v${featherVersion} (MIT) · Tabler Icons v${tablerVersion} (MIT).
   Neither is a dependency of the lib: morphicons consumes structural IconNode. */

import type { IconNode } from "../src/index";

export const FEATHER: Record<string, IconNode> = {
${entries(FEATHER_PICK, (n) => parseContents(feather[n]))}
};

export const TABLER: Record<string, IconNode> = {
${entries(TABLER_PICK, (n) => tabler[n])}
};
`;

writeFileSync("playground/vendor-icons.ts", out);
console.log(
  `OK → playground/vendor-icons.ts (${FEATHER_PICK.length} feather, ${TABLER_PICK.length} tabler)`,
);
